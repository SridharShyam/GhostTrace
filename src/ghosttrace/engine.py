def detect_translation_artifacts(text):
    """Detects syntactic calques, false friends, and machine translation artifacts.
    
    Identifies non-English linguistic structures literally translated into English by LLMs.
    """
    artifacts_found = []
    category_counts = collections.defaultdict(int)
    
    for language_family, rules in TRANSLATION_CALQUES.items():
        for pattern, explanation in rules:
            matches = re.findall(pattern, text, re.IGNORECASE)
            if matches:
                for m in matches:
                    artifacts_found.append({
                        "phrase": m,
                        "origin_family": language_family.replace("_", " ").title(),
                        "recommendation": explanation
                    })
                    category_counts[language_family] += 1
                    
    total_artifacts = len(artifacts_found)
    has_artifacts = total_artifacts > 0
    
    return {
        "has_translation_artifacts": has_artifacts,
        "total_artifacts": total_artifacts,
        "category_breakdown": dict(category_counts),
        "artifacts": artifacts_found,
        "verdict": f"Flagged {total_artifacts} literal AI translation calques" if has_artifacts else "Clean: Natural English phrasing without translationese"
    }

# 5. Local N-Gram Glider & Perplexity Cadence Profiler
def profile_ngrams_and_perplexity(text):
    """Glides across text using n-grams to detect repetitive sentence head words and low-entropy sequences.
    
    Calculates:
      1. Anaphora stacking (consecutive sentences starting with identical head words).
      2. Repetitive 3-grams and 4-grams (robotic phrase recycling).
      3. Per-sentence lexical variation profile.
    """
    raw_sentences = re.split(r'(?<=[.!?])\s+', text.strip())
    sentences = [s.strip() for s in raw_sentences if len(s.strip().split()) >= 3]
    
    if len(sentences) < 2:
        return {
            "sentence_count": len(sentences),
            "repetitive_head_words": [],
            "recycled_ngrams": [],
            "lexical_diversity_ratio": 1.0,
            "verdict": "Text too short for n-gram cadence profiling (min 2 sentences)"
        }
        
    # 1. Anaphora & Head Word Stacking Check
    head_words = []
    consecutive_stacking = []
    for i, s in enumerate(sentences):
        words = s.split()
        first_two = " ".join(words[:2]).lower() if len(words) >= 2 else words[0].lower()
        head_words.append(first_two)
        if i > 0 and first_two == head_words[i - 1]:
            consecutive_stacking.append({
                "sentence_index": i + 1,
                "repeated_head": first_two,
                "context": s[:60] + "..."
            })
            
    # 2. Rolling 3-Gram & 4-Gram Recycling
    tokens = re.findall(r'\b[a-zA-Z]{3,}\b', text.lower())
    three_grams = [f"{tokens[i]} {tokens[i+1]} {tokens[i+2]}" for i in range(len(tokens) - 2)]
    trigram_counts = collections.Counter(three_grams)
    recycled_ngrams = [
        {"ngram": ng, "count": c} for ng, c in trigram_counts.most_common(5) if c >= 3
    ]
    
    # 3. Type-Token Ratio (Lexical Diversity)
    unique_tokens = len(set(tokens))
    total_tokens = len(tokens)
    ttr = round(unique_tokens / max(1, total_tokens), 3)
    
    is_robotic_cadence = len(consecutive_stacking) >= 2 or len(recycled_ngrams) >= 2 or (ttr < 0.45 and total_tokens > 50)
    
    return {
        "sentence_count": len(sentences),
        "lexical_diversity_ratio": ttr,
        "consecutive_head_word_stacking": consecutive_stacking,
        "recycled_ngrams": recycled_ngrams,
        "is_robotic_cadence": is_robotic_cadence,
        "verdict": "Robotic N-Gram Cadence Detected (Repetitive sentence openers or recycled trigrams)" if is_robotic_cadence else "Healthy Natural N-Gram Cadence"
    }

def normalise(t):
    """Normalize typographic quotes, dashes, spaces and purge invisible watermarks."""
    t = sanitize_watermarks(t)
    t = t.replace('’', "'").replace('“', '"').replace('”', '"')
    return re.sub(r'\s+', ' ', t).strip()

def read_utf8(path):
    """Read file safely in UTF-8 encoding."""
    return open(path, encoding='utf-8', errors='replace').read()

def visible_text_html(html):
    """Strip script, styles, and tags from HTML."""
    t = re.sub(r'<(script|style)\b.*?</\1>', ' ', html, flags=re.S | re.I)
    t = re.sub(r'<!--.*?-->', ' ', t, flags=re.S)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = _html.unescape(t)
    return normalise(t)

def markdown_prose(md):
    """Strip markdown code blocks, links, specimens."""
    md = re.sub(r'```.*?```', ' ', md, flags=re.S)
    md = re.sub(r'!\[[^\]]*\]\([^)]*\)', ' . ', md)
    md = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', md)
    md = re.sub(r'`[^`]*`', ' it ', md)
    md = re.sub(r'~~.*?~~', ' it ', md, flags=re.S)
    md = re.sub(r'^\s{0,3}#{1,6}\s*(.*)$', r' . \1 . ', md, flags=re.M)
    md = re.sub(r'\|', ' . ', md)
    md = re.sub(r'^\s*(?:[-*+]|\d+\.)\s+', ' . ', md, flags=re.M)
    md = re.sub(r'^\s*>\s?', ' . ', md, flags=re.M)
    md = re.sub(r'[*_>]', ' ', md)
    return normalise(md)

def latex_prose(tex):
    """Extract natural readable prose from LaTeX documents.

    Strips:
      - Comments (% ...)
      - Preamble / document control environments
      - Inline math ($...$) and Display math (\\[...\\] or equation environments)
      - Citations (\\cite{...}, \\citep{...}) and references (\\ref{...}, \\label{...})
      - Common macros like \\textbf{...}, \\emph{...} preserving the inner text
    """
    # Remove comments
    tex = re.sub(r'(?<!\\)%.*$', '', tex, flags=re.M)

    # Remove display math environments
    tex = re.sub(r'\\begin\{(equation|align|gather|multline|matrix|bmatrix|table|figure)\*?\}.*?\\end\{\1\*?\}', ' . ', tex, flags=re.S)
    tex = re.sub(r'\\\[.*?\\\]', ' . ', tex, flags=re.S)

    # Remove inline math ($ ... $)
    tex = re.sub(r'\$[^\$]+\$', ' math-term ', tex)

    # Remove citations & references
    tex = re.sub(r'\\(?:cite|citep|citet|nocite|ref|pageref|label|eqref)\{[^}]*\}', ' ', tex)

    # Convert common LaTeX formatting commands to inner text: \textbf{text} -> text
    tex = re.sub(r'\\(?:textbf|textit|emph|underline|text|mathrm|textsf)\{([^}]*)\}', r'\1', tex)

    # Replace section headers with punctuation boundaries
    tex = re.sub(r'\\(?:section|subsection|subsubsection|paragraph)\*?\{([^}]*)\}', r' . \1 . ', tex)

    # Strip other backslashed commands
    tex = re.sub(r'\\[a-zA-Z]+(?:\*|\[[^\]]*\])?', ' ', tex)

    # Clean braces
    tex = tex.replace('{', ' ').replace('}', ' ')

    return normalise(tex)

# ── 3. Statistical Burstiness & Pacing Analyzer ───────────────────────────────

def analyze_burstiness(text):
    """Calculates statistical pacing, Shannon lexical entropy, and syntactic cadence.

    Human writing features high standard deviation in sentence lengths (punchy short
    sentences alternating with complex compound sentences) and high lexical entropy.
    AI models typically output monotonous sentence lengths (12-18 words) with low
    variance and formulaic syntactic depth.
    """
    raw_sentences = re.split(r'(?<=[.!?])\s+', text)
    sentences = [s.strip() for s in raw_sentences if len(s.strip().split()) >= 3]

    words = re.findall(r'\b[a-z]{2,}\b', text.lower())
    total_words = len(words)

    # 1. Shannon Lexical Entropy calculation
    entropy = 0.0
    if total_words > 0:
        counts = {}
        for w in words:
            counts[w] = counts.get(w, 0) + 1
        for count in counts.values():
            p = count / total_words
            entropy -= p * math.log2(p)

    # 2. Passive Voice Density Estimation (passive aux + past participle)
    passive_matches = len(re.findall(
        r'\b(?:is|are|was|were|be|been|being)\s+([a-z]{3,}ed|[a-z]{3,}en|built|done|made|found|shown|proven|written|held)\b',
        text.lower()
    ))
    passive_ratio = round((passive_matches / max(1, len(sentences))) * 100, 1)

    if len(sentences) < 3:
        return {
            'score': 'N/A (text too short)',
            'std_dev': 0,
            'avg_len': 0,
            'is_monotonous': False,
            'sentence_lengths': [len(s.split()) for s in sentences],
            'entropy': round(entropy, 2),
            'passive_ratio': passive_ratio,
            'min_len': min([len(s.split()) for s in sentences]) if sentences else 0,
            'max_len': max([len(s.split()) for s in sentences]) if sentences else 0
        }

    lengths = [len(s.split()) for s in sentences]
    avg = sum(lengths) / len(lengths)
    variance = sum((l - avg) ** 2 for l in lengths) / len(lengths)
    std_dev = math.sqrt(variance)

    # Standard deviation < 3.5 across 5+ sentences is a classic indicator of AI cadence
    is_monotonous = (std_dev < 3.2 and len(sentences) >= 5) or (std_dev < 5.0 and len(sentences) >= 10)

    return {
        'total_sentences': len(sentences),
        'avg_len': round(avg, 1),
        'std_dev': round(std_dev, 2),
        'is_monotonous': is_monotonous,
        'sentence_lengths': lengths,
        'entropy': round(entropy, 2),
        'passive_ratio': passive_ratio,
        'min_len': min(lengths),
        'max_len': max(lengths)
    }

# ── 4. Audit Engine ───────────────────────────────────────────────────────────

def audit(text, mode='general'):
    """Audit text for AI tells.

    mode: 'general' | 'academic'
    """
    hits = {
        'vocab': [],
        'phrases': [],
        'punctuation': [],
        'rhythm': [],
        'proof': [],
        'academic_hype': [],
    }
    low = text.lower()

    # 1. Vocabulary
    vocab_list = list(VOCAB_BASE)
    if mode != 'academic':
        vocab_list.extend(VOCAB_GENERAL_ONLY)

    for w in vocab_list:
        n = len(re.findall(_root_pattern(w), low))
        if n:
            hits['vocab'].append((w, n))

    for w in VOCAB_EXACT:
        n = len(re.findall(rf"(?<!\w){re.escape(w)}(?!\w)", low))
        if n:
            hits['vocab'].append((w, n))

    # 2. Phrases
    active_phrases = list(BASE_PHRASES)
    if mode == 'academic':
        active_phrases.extend(ACADEMIC_PHRASES)
    elif mode in ['creative', 'narrative', 'story']:
        active_phrases.extend(NARRATIVE_PHRASES)
    elif mode in ['essay', 'student', 'grant']:
        active_phrases.extend(ESSAY_PHRASES)
    else:
        # General mode includes narrative and essay safeguards
        active_phrases.extend(NARRATIVE_PHRASES)
        active_phrases.extend(ESSAY_PHRASES)

    for pat, label in active_phrases:
        found = re.findall(pat, low)
        if found:
            # Extract matches with full matched strings for UI highlighting
            raw_matches = [m.group(0) for m in re.finditer(pat, text, flags=re.I)]
            hits['phrases'].append((label, len(found), raw_matches))

    # 3. Academic Hype (if academic mode)
    if mode == 'academic':
        for hype in ACADEMIC_HYPE:
            n = len(re.findall(rf"(?<!\w){re.escape(hype)}(?!\w)", low))
            if n:
                hits['academic_hype'].append((hype, n))

    # 4. Punctuation Cadence (Em-dashes, stacked compounds, semicolons)
    for s in re.split(r'(?<=[.!?])\s+', text):
        for i in range(0, max(1, len(s)), 220):
            window = s[i:i + 220]
            if window.count('—') >= 2:
                hits['punctuation'].append(('two or more em-dashes in one sentence', window[:70].strip()))
                break

    for s in re.split(r'(?<=[.!?])\s+', text):
        for i in range(0, max(1, len(s)), 220):
            window = s[i:i + 220]
            found = COMPOUND.findall(window)
            if len(found) >= COMPOUND_FLOOR:
                hits['punctuation'].append((f'{len(found)} hyphenated compounds stacked', ', '.join(found[:4])))
                break

    if text.count(';') > max(3, len(text) // 1200):
        hits['punctuation'].append(('semicolon-heavy cadence', f"{text.count(';')} found"))

    # 5. Rule-of-three cadence
    for pat in (r'\b(\w{4,}),\s+(\w{4,}),\s+and\s+(\w{4,})\b',
                r'\b(\w{4,}),\s+(\w{4,})\s+and\s+((?:\w+\s+){1,2}\w+)\s*[.!?,;:]'):
        for m in re.finditer(pat, text):
            hits['rhythm'].append(('rule-of-three list', m.group(0)[:60]))

    # 6. Unsubstantiated proof claims
    for m in PROOF.finditer(text):
        hits['proof'].append(m.group(0).strip())

    return hits


# ── 7. Reporting & CLI ────────────────────────────────────────────────────────

def calculate_score(hits, word_count=0, allow_proof=False, burst=None):
    """Calculates score based on both categorical violations and AI word density.

    1. Base categorical penalty: -1 per triggered category.
    2. Density penalty: If AI buzzwords constitute a high percentage of the copy:
       - >= 10% density: -3 penalty
       - >= 5% density:  -2 penalty
       - >= 2.5% density: -1 penalty
    3. Cadence / Burstiness penalty:
       - If >= 5 sentences and std_dev < 2.5 (unnatural LLM uniformity): -1 penalty
    """
    weights = {'vocab': 1, 'phrases': 1, 'punctuation': 1, 'rhythm': 1, 'proof': 1, 'academic_hype': 1}
    if allow_proof:
        weights['proof'] = 0

    failed = [k for k, v in hits.items() if v]
    category_penalty = sum(weights[k] for k in failed if k in weights)

    # Calculate total AI vocabulary and phrase occurrences
    total_vocab_hits = sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('vocab', []))
    total_vocab_hits += sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('academic_hype', []))
    
    total_phrase_hits = sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('phrases', []))

    # Multi-phrase penalty: If multiple distinct AI constructions are packed into one short text, dock points
    phrase_penalty = max(0, total_phrase_hits - 1) if (word_count > 0 and word_count < 60) else 0

    density_penalty = 0
    total_tells = total_vocab_hits + total_phrase_hits
    if word_count > 0 and total_tells > 0:
        density = (total_tells / word_count) * 100
        if density >= 10.0:
            density_penalty = 3
        elif density >= 5.0:
            density_penalty = 2
        elif density >= 2.5:
            density_penalty = 1

    # Burstiness penalty: severely flat sentence length cadence across >= 5 sentences
    burst_penalty = 0
    if burst and burst.get('total_sentences', 0) >= 5 and burst.get('is_monotonous', False):
        burst_penalty = 1

    total_penalty = max(category_penalty, category_penalty + density_penalty + phrase_penalty + burst_penalty)
    # If any category triggered or cadence is flat, score can never be 5.
    if failed or burst_penalty > 0:
        total_penalty = max(1, total_penalty)

    return max(0, 5 - total_penalty), total_vocab_hits, density_penalty, total_phrase_hits


def calculate_score(hits, word_count=0, allow_proof=False):
    """Calculates score based on both categorical violations and AI word density.

    1. Base categorical penalty: -1 per triggered category.
    2. Density penalty: If AI buzzwords constitute a high percentage of the copy:
       - >= 10% density: -3 penalty
       - >= 5% density:  -2 penalty
       - >= 2.5% density: -1 penalty
    """
    weights = {'vocab': 1, 'phrases': 1, 'punctuation': 1, 'rhythm': 1, 'proof': 1, 'academic_hype': 1}
    if allow_proof:
        weights['proof'] = 0

    failed = [k for k, v in hits.items() if v]
    category_penalty = sum(weights[k] for k in failed if k in weights)

    # Calculate total AI vocabulary and phrase occurrences
    total_vocab_hits = sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('vocab', []))
    total_vocab_hits += sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('academic_hype', []))
    
    total_phrase_hits = sum(item[1] if isinstance(item, tuple) and len(item) > 1 else 1 for item in hits.get('phrases', []))

    # Multi-phrase penalty: If multiple distinct AI constructions are packed into one short text, dock points
    phrase_penalty = max(0, total_phrase_hits - 1) if (word_count > 0 and word_count < 60) else 0

    density_penalty = 0
    total_tells = total_vocab_hits + total_phrase_hits
    if word_count > 0 and total_tells > 0:
        density = (total_tells / word_count) * 100
        if density >= 10.0:
            density_penalty = 3
        elif density >= 5.0:
            density_penalty = 2
        elif density >= 2.5:
            density_penalty = 1

    total_penalty = max(category_penalty, category_penalty + density_penalty + phrase_penalty)
    # If any category triggered, score can never be 5.
    if failed:
        total_penalty = max(1, total_penalty)

    return max(0, 5 - total_penalty), total_vocab_hits, density_penalty, total_phrase_hits

def report(hits, burst, raw_text='', word_count=0, label='', allow_proof=False, suggest=False):
    score, total_vocab_hits, density_penalty, total_phrase_hits = calculate_score(hits, word_count=word_count, allow_proof=allow_proof)

    titles = {
        'vocab': 'AI vocabulary tells',
        'phrases': 'AI constructions',
        'academic_hype': 'academic hype & unverified claims',
        'punctuation': 'punctuation cadence',
        'rhythm': 'rule-of-three rhythm',
        'proof': 'possible unsupported social proof',
    }

    if label:
        print(f'== {label}')

    for k in ('proof', 'phrases', 'academic_hype', 'vocab', 'punctuation', 'rhythm'):
        if not hits.get(k):
            continue
        print(f'  {titles[k]}:')
        for item in hits[k][:8]:
            print(f'    * {item[0] if isinstance(item, tuple) else item}'
                  + (f'  ({item[1]})' if isinstance(item, tuple) and len(item) > 1 else ''))
        if len(hits[k]) > 8:
            print(f'    * ...and {len(hits[k]) - 8} more')

    # Burstiness Diagnosis
    if burst.get('total_sentences', 0) >= 5:
        print(f'\n  cadence & burstiness: std_dev = {burst["std_dev"]} (avg {burst["avg_len"]} words/sentence)')
        if burst['is_monotonous']:
            print('    [!] Warning: Flat sentence length cadence detected (classic AI signature)')

    # Watermark Steganography Report
    watermarks = detect_watermarks(raw_text if raw_text else "")
    if watermarks:
        print('\n  [!] Intrinsic AI Watermarks / Unicode Steganography Detected:')
        for name, count in watermarks.items():
            print(f'    * {name}: {count} instance(s) found')

    # Suggestions / Replacements
    if suggest:
        suggestions = get_suggestions(hits)
        if suggestions:
            print('\n  recommended human replacements:')
            for word, alts in suggestions[:8]:
                print(f'    * "{word}" -> {", ".join(alts[:3])}')

    if density_penalty > 0 and word_count > 0:
        density = (total_vocab_hits / word_count) * 100
        print(f'\n  [!] Heavy AI Buzzword Saturation: {density:.1f}% of words flagged (-{density_penalty} score penalty)')

    print(f'\n  score {score}/5', end='  ')
    print('CLEAN' if score == 5 else 'needs a cleanse')
    return score

